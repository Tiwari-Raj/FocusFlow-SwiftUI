import Foundation

/// The three phases of a Pomodoro cycle.
/// Shared between the app target and the Widget Extension (Live Activity),
/// so it must be added to BOTH target memberships in Xcode.
enum PomodoroPhase: String, Codable, CaseIterable, Identifiable {
    case focus
    case shortBreak
    case longBreak

    var id: String { rawValue }

    var title: String {
        switch self {
        case .focus: return "Focus"
        case .shortBreak: return "Short Break"
        case .longBreak: return "Long Break"
        }
    }

    var systemImage: String {
        switch self {
        case .focus: return "brain.head.profile"
        case .shortBreak: return "cup.and.saucer.fill"
        case .longBreak: return "leaf.fill"
        }
    }
}
